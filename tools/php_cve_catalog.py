def fetch_url(url):
    request = urllib.request.Request(url, headers={"User-Agent": "phego-cve-catalog"})
    with urllib.request.urlopen(request, timeout=180) as response:
        body = response.read(MAX_RESPONSE + 1)
    if len(body) > MAX_RESPONSE:
        raise ValueError(f"{url} exceeds {MAX_RESPONSE} bytes")
    return body


def fetch_advisories(cache, manifest, opener=urllib.request.urlopen):
    """Download php-src's security advisories, one file per page."""
    # The advisories endpoint pages by cursor (Link: rel="next"); it
    # ignores page=, which would return the first page forever.
    url, page_number, seen = ADVISORIES, 1, set()
    while url:
        request = urllib.request.Request(url, headers={"User-Agent": "phego-cve-catalog", "Accept": "application/vnd.github+json"})
        with opener(request, timeout=180) as response:
            body = response.read(MAX_RESPONSE + 1)
            link = response.headers.get("Link", "")
        if len(body) > MAX_RESPONSE:
            raise ValueError(f"{url} exceeds {MAX_RESPONSE} bytes")
        page = json.loads(body)
        if not isinstance(page, list):
            raise ValueError(f"{url} did not return a list of advisories")
        ids = {a["ghsa_id"] for a in page}
        if ids & seen:
            raise ValueError(f"{url} repeated advisories {sorted(ids & seen)}; the paging changed")
        seen |= ids
        name = f"ghsa-{page_number}.json"
        (cache / name).write_bytes(body)
        manifest["files"][name] = {"url": url, "sha256": hashlib.sha256(body).hexdigest()}
        nxt = re.search(r'<([^>]+)>;\s*rel="next"', link)
        if nxt and not page:
            raise ValueError(f"{url} returned no advisories but a next page")
        if nxt and not nxt.group(1).startswith("https://api.github.com/"):
            raise ValueError(f"{url} points its next page outside api.github.com")
        url, page_number = (nxt.group(1) if nxt else None), page_number + 1


def fetch(cache):
    cache.mkdir(parents=True, exist_ok=True)
    manifest = {"fetched_at": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "files": {}}
    pages, start = [], 0
    while True:
        body = fetch_url(NVD.format(start))
        data = json.loads(body)
        name = f"nvd-{start}.json"
        (cache / name).write_bytes(body)
        manifest["files"][name] = {"url": NVD.format(start), "sha256": hashlib.sha256(body).hexdigest()}
        pages.append(data)
        start += len(data["vulnerabilities"])
        if start >= data["totalResults"] or not data["vulnerabilities"]:
            break
        time.sleep(7)  # the public NVD API allows 5 requests in 30 seconds
    for major, url in CHANGELOGS.items():
        body = fetch_url(url)
        name = f"ChangeLog-{major}.html"
        (cache / name).write_bytes(body)
        manifest["files"][name] = {"url": url, "sha256": hashlib.sha256(body).hexdigest()}
    fetch_advisories(cache, manifest)
    listing = subprocess.run(["docker", "run", "--rm", "--network", "none", PHP_IMAGE, "sh", "-c",
                              "tar -tJf /usr/src/php.tar.xz"], capture_output=True, timeout=600, check=True).stdout
    (cache / PHP_SOURCE_LIST).write_bytes(listing)
    manifest["files"][PHP_SOURCE_LIST] = {"url": f"docker run {PHP_IMAGE} tar -tJf /usr/src/php.tar.xz",
                                          "sha256": hashlib.sha256(listing).hexdigest()}
    (cache / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"fetched {start} NVD records and {len(CHANGELOGS)} ChangeLogs into {cache}")


def text_of(fragment):
    return " ".join(html.unescape(TAG.sub("", fragment)).split())


def norm_section(name):
    name = html.unescape(name).strip().lower()
    for prefix in ("improved ",):
        if name.startswith(prefix):
            name = name[len(prefix):]
    for suffix in (" extension", " extesion", " sapi", " driver", " support (pierre)", " support"):
        if name.endswith(suffix):
            name = name[: -len(suffix)]
    name = name.replace("pdo_", "pdo ").replace("pdo-", "pdo ").replace("pdo/", "pdo ")
    if name.startswith("pdo "):
        return "pdo"
    if name.startswith("zend engine"):
        return "zend engine"
    if name.startswith("oracle database"):
        return "oci8"
    return name


def parse_changelog(major, body):
    """Return {id: [{"release", "section", "text"}]} for one ChangeLog page.

    Every identifier that appears anywhere in the page must be captured by a
    list item inside a version section; otherwise the page layout changed and
    the parse fails rather than skip an advisory.
    """
    page = SPACED_CVE.sub(r"CVE-\1", body.decode("utf-8"))
    odd = sorted({m for m in LOOSE_CVE.findall(page) if not ID.fullmatch(m)})
    if odd:
        raise ValueError(f"ChangeLog-{major}: identifiers in an unknown spelling: {odd}")
    found = {}
    starts = list(VERSION_SECTION.finditer(page))
    if not starts:
        raise ValueError(f"ChangeLog-{major}: no version sections")
    for i, start in enumerate(starts):
        end = starts[i + 1].start() if i + 1 < len(starts) else len(page)
        block = page[start.end():end]
        headers = [(m.start(), m.group(1)) for m in SECTION_HEADER.finditer(block)]
        for item in ITEM.finditer(block):
            ids = sorted(set(ID.findall(item.group(1))))
            if not ids:
                continue
            section = None
            for pos, name in headers:
                if pos < item.start():
                    section = name
            text = text_of(item.group(1))
            for ident in ids:
                found.setdefault(ident, []).append({"release": start.group(1), "section": norm_section(section) if section else None, "text": text})
    everywhere = set(ID.findall(page))
    missed = everywhere - set(found)
    if missed:
        raise ValueError(f"ChangeLog-{major}: identifiers outside any parsed item: {sorted(missed)}")
    return found


def load_sources(cache):
    nvd = {}
    for path in sorted(cache.glob("nvd-*.json")):
        for v in json.loads(path.read_text())["vulnerabilities"]:
            nvd[v["cve"]["id"]] = v["cve"]
    if not nvd:
        raise ValueError(f"no NVD pages in {cache}; run fetch first")
    changelog = {}
    for major in CHANGELOGS:
        for ident, items in parse_changelog(major, (cache / f"ChangeLog-{major}.html").read_bytes()).items():
            changelog.setdefault(ident, []).extend(items)
    advisories = {}
    for path in sorted(cache.glob("ghsa-*.json")):
        page = json.loads(path.read_text())
        if not isinstance(page, list):
            raise ValueError(f"{path.name} is not a list of advisories")
        for a in page:
            advisories[a["ghsa_id"]] = {"cve": a.get("cve_id"), "summary": " ".join((a.get("summary") or "").split()),
                                        "published": (a.get("published_at") or "")[:10]}
    if not advisories:
        raise ValueError(f"no php-src advisory pages in {cache}; run fetch first")
    return nvd, changelog, advisories


def php_vulnerable(cve):
    for config in cve.get("configurations", []):
        for node in config["nodes"]:
            for match in node["cpeMatch"]:
                if match["criteria"].startswith("cpe:2.3:a:php:php:") and match["vulnerable"]:
                    return True
    return False


def other_products(cve):
    products = set()
    for config in cve.get("configurations", []):
        for node in config["nodes"]:
            for match in node["cpeMatch"]:
                if match["vulnerable"]:
                    parts = match["criteria"].split(":")
                    products.add(f"{parts[3]}:{parts[4]}")
    return sorted(products)


def nvd_cwes(cve):
    cwes = set()
    for weakness in cve.get("weaknesses", []):
        for d in weakness["description"]:
            if d["value"].startswith("CWE-"):
                cwes.add(d["value"])
    return sorted(cwes, key=lambda c: int(c[4:]))


def nvd_description(cve):
    for d in cve.get("descriptions", []):
        if d["lang"] == "en":
            return " ".join(d["value"].split())
    return ""


def short(text):
    return text if len(text) <= SUMMARY_LIMIT else text[: SUMMARY_LIMIT - 1].rstrip() + "…"


def extract(nvd, changelog, advisories):
    """Merge the sources into source records, one per identifier.

    php-src's GitHub advisories map each GHSA to its CVE, and so does a
    ChangeLog line that names both when it names one of each; the CVE is the
    entry and the GHSA becomes an alias that lends it its ChangeLog lines. A
    GHSA without a CVE is its own entry.
    """
    aliases = {}
    for ghsa, a in advisories.items():
        if a["cve"]:
            aliases.setdefault(a["cve"], set()).add(ghsa)
    mapped = {g for gs in aliases.values() for g in gs}
    for ident, items in changelog.items():
        if ident.startswith("GHSA") and ident not in mapped:
            for item in items:
                cves = sorted({o for o in ID.findall(item["text"]) if o.startswith("CVE-")})
                ghsas = {o for o in ID.findall(item["text"]) if o.startswith("GHSA")}
                if len(cves) == 1 or len(ghsas) == 1:
                    for other in cves:
                        aliases.setdefault(other, set()).add(ident)
    aliased = {g for gs in aliases.values() for g in gs}
    records = {}
    for ident in sorted(set(nvd) | set(changelog) | set(advisories) | set(aliases)):
        if ident in aliased:
            continue
        cve = nvd.get(ident)
        items = list(changelog.get(ident, []))
        for alias in sorted(aliases.get(ident, ())):
            items += [i for i in changelog.get(alias, []) if i not in items]
        rec = {"id": ident, "aliases": sorted(aliases.get(ident, ())), "sources": []}
        if cve:
            rec["sources"].append("nvd")
            rec["published"] = cve["published"][:10]
            rec["nvd_status"] = cve.get("vulnStatus", "")
            rec["cwe"] = nvd_cwes(cve)
            rec["summary"] = short(nvd_description(cve))
            rec["php_vulnerable_in_nvd"] = php_vulnerable(cve)
            if not rec["php_vulnerable_in_nvd"]:
                rec["nvd_products"] = other_products(cve)
        advisory = [advisories[g] for g in [ident, *rec["aliases"]] if g in advisories]
        if advisory:
            rec["sources"].append("php-src-advisory")
            rec.setdefault("summary", short(advisory[0]["summary"]))
            rec.setdefault("published", advisory[0]["published"])
        if items:
            rec["sources"].append("php.net-changelog")
            seen, notes = set(), []
            for item in items:
                key = (item["section"], item["text"])
                if key not in seen:
                    seen.add(key)
                    notes.append({"section": item["section"], "text": short(item["text"])})
            rec["fixed_in"] = sorted({i["release"] for i in items}, key=version_key)
            rec["changelog"] = notes
        records[ident] = rec
    return records


def upstream_tests(records, listing):
    """Name the php-src 8.5.12 tests for each record's bug numbers and advisories."""
    tests = [p for p in listing.splitlines() if p.endswith(".phpt")]
    by_bug, by_gh, by_ghsa = {}, {}, {}
    for path in tests:
        name = path.rsplit("/", 1)[-1].lower()
        m = re.match(r"(bug|gh-?)(\d{3,6})(?:[_.-]|\.phpt|[a-z]\.phpt)", name)
        if m:
            table = by_bug if m.group(1) == "bug" else by_gh
            table.setdefault(m.group(2), []).append(path.split("/", 1)[1])
        g = re.match(r"(ghsa(?:-[23456789cfghjmpqrvwx]{4}){3})", name)
        if g:
            by_ghsa.setdefault(g.group(1), []).append(path.split("/", 1)[1])
    for rec in records.values():
        found = set()
        for note in rec.get("changelog", []):
            text = GH_NUMBER.sub("", note["text"])
            for number in BUG_NUMBER.findall(text):
                found.update(by_bug.get(number, []))
            for number in GH_NUMBER.findall(note["text"]):
                found.update(by_gh.get(number, []))
        for ident in [rec["id"], *rec["aliases"]]:
            found.update(by_ghsa.get(ident.lower(), []))
        if found:
            rec["php_src_tests"] = sorted(found)


def version_key(v):
    return [int(p) if p.isdigit() else -1 for p in re.split(r"[.]", re.sub(r"[^0-9.]", ".", v)) if p != ""]


def classify(rec):
    """Apply the rules to one source record; return (component, class, rule)."""
    section = None
    for n in rec.get("changelog", []):
        if n["section"] in SECTIONS:
            section = SECTIONS[n["section"]]
            break
    text = " ".join([n["text"] for n in rec.get("changelog", [])] + [rec.get("summary", "")]).lower()
    keyword = next((name for name, pattern in KEYWORDS if re.search(pattern, text)), None)
    if section is None:
        component, rule = (keyword, "keyword") if keyword else ("engine", "default")
    elif section in BROAD_SECTIONS and keyword not in (None, section, "engine", "parser"):
        # "Core" and "Standard" hold function-level fixes too: unserialize,
        # uploads and open_basedir checks belong to their own component.
        component, rule = keyword, "keyword-over-section"
    else:
        component, rule = section, "changelog-section"
    # A memory defect named in the text decides the class before a generic
    # CWE such as CWE-399 or CWE-20 can.
    cls = "memory-safety" if re.search(CLASS_RULES[0][1], text) else None
    cwes = set(rec.get("cwe", []))
    if cls is None:
        for name, ids in (("memory-safety", MEMORY_CWES), ("resource-exhaustion", RESOURCE_CWES), ("injection", INJECTION_CWES),
                          ("policy-bypass", POLICY_CWES), ("crypto", CRYPTO_CWES), ("disclosure", DISCLOSURE_CWES)):
            if cwes & ids:
                cls = name
                break
    if cls is None:
        cls = next((name for name, pattern in CLASS_RULES[1:] if re.search(pattern, text)), "logic")
    return component, cls, rule


def load_triage():
    data = json.loads(TRIAGE.read_text())
    if data.get("schema_version") != SCHEMA:
        raise ValueError(f"{TRIAGE.name}: schema_version must be {SCHEMA}")
    return data


def catalog_entries(records, triage):
    """Classify every record and apply the reviewed triage on top."""
    reviewed = triage["entries"]
    unknown = sorted(set(reviewed) - set(records))
    if unknown:
        raise ValueError(f"{TRIAGE.name} names identifiers that are in no source: {unknown}")
    entries = []
    for ident, rec in sorted(records.items(), key=lambda kv: id_key(kv[0])):
        component, cls, rule = classify(rec)
        entry = dict(rec)
        entry.update({"component": component, "defect_class": cls, "classified_by": rule})
        if ident not in reviewed:
            raise ValueError(f"{ident}: no record in {TRIAGE.name}; review its component and defect class and add one")
        t = reviewed[ident]
        for field in ("component", "defect_class"):
            if field in t:
                entry[field] = t[field]
        if t:
            entry["classified_by"] = "reviewed"
        if t.get("note"):
            entry["note"] = t["note"]
        comp = COMPONENTS[entry["component"]]
        if t.get("excluded"):
            entry["status"], entry["work_package"] = "excluded", None
            entry["note"] = t["excluded"]
        elif ("nvd" in rec["sources"] and not rec["php_vulnerable_in_nvd"]
              and "php.net-changelog" not in rec["sources"] and not t.get("note")):
            raise ValueError(f"{ident}: NVD lists php:php only as a platform for {rec['nvd_products']}; "
                             f"exclude it in {TRIAGE.name} with the reason, or keep it with a note")
        elif rec.get("nvd_status") == "Rejected":
            raise ValueError(f"{ident}: NVD rejected this record; exclude it in {TRIAGE.name} with the reason")
        elif comp.get("not_provided"):
            entry["status"], entry["work_package"] = "not-provided", None
            entry["note"] = t.get("note") or comp["not_provided"]
        else:
            entry["work_package"] = comp["wp"]
            entry["status"] = "tested" if t.get("tests") else "pending"
        entry["tests"] = sorted(t.get("tests", []))
        if entry["tests"] and entry["status"] != "tested":
            raise ValueError(f"{ident}: only an entry Phego provides can carry tests")
        if entry["status"] in ("tested", "pending") and fixed_after_pinned(rec):
            # PHP_IMAGE still has this bug, so its output is not the expected
            # result: the note says what the fix requires, and no case can
            # take that image as its reference.
            if not t.get("note"):
                raise ValueError(f"{ident}: fixed after {PINNED_RELEASE}; its note must state the behaviour the fix requires")
            if entry["tests"]:
                raise ValueError(f"{ident}: fixed after {PINNED_RELEASE}, so the pinned image cannot record its expected output")
        if entry["status"] == "pending" and comp.get("implemented") and not t.get("note"):
            raise ValueError(f"{ident}: {entry['component']} already runs; its note must name what a case still waits for")
        if entry["status"] == "tested":
            entry["coverage"] = t.get("coverage", "full")
            if entry["coverage"] not in ("full", "partial"):
                raise ValueError(f"{ident}: coverage must be full or partial")
            if entry["coverage"] == "partial" and not t.get("note"):
                raise ValueError(f"{ident}: a partial case needs a note naming what it leaves out")
        entries.append(entry)
    return entries


def fixed_after_pinned(rec):
    """The pinned release still has the bug: no release of its branch up to
    it carries the fix, and a later release (on any branch) does."""
    series = PINNED_RELEASE.rsplit(".", 1)[0] + "."
    pinned = version_key(PINNED_RELEASE)
    fixed = rec.get("fixed_in", [])
    if any(v.startswith(series) and version_key(v) <= pinned for v in fixed):
        return False
    return any(version_key(v) > pinned for v in fixed)


def id_key(ident):
    if ident.startswith("CVE-"):
        _, year, num = ident.split("-")
        return (0, int(year), int(num), "")
    return (1, 0, 0, ident)


def document(entries, sources):
    counts = Counter(e["status"] for e in entries)
    return {
        "schema_version": SCHEMA,
        "description": "Every CVE and GHSA advisory NVD files against php:php or a php.net ChangeLog names, with the Phego component, defect class, work package and regression cases. Generated by tools/php_cve_catalog.py build; tests/security/php-cve holds the cases.",
        "sources": sources,
        "components": {k: {kk: vv for kk, vv in v.items()} for k, v in COMPONENTS.items()},
        "totals": {s: counts.get(s, 0) for s in STATUSES} | {"entries": len(entries)},
        "entries": entries,
    }


def encode(data):
    return json.dumps(data, ensure_ascii=False, indent=1, sort_keys=True) + "\n"


def readme_block(doc):
    entries = doc["entries"]
    tracked = [e for e in entries if e["status"] in ("tested", "pending")]
    tested = [e for e in entries if e["status"] == "tested"]
    partial = sum(1 for e in tested if e["coverage"] == "partial")
    pending = len(tracked) - len(tested)
    memory = sum(1 for e in tracked if e["defect_class"] == "memory-safety")
    by_wp = Counter(e["work_package"] for e in entries if e["status"] == "pending")
    years = sorted(int(e["published"][:4]) for e in entries if e.get("published"))
    cases = len({c for e in tested for c in e["tests"]})
    lines = [
        README_BEGIN,
        "## Every published PHP vulnerability, tracked",
        "",
        f"Phego's catalog lists all {doc['totals']['entries']} vulnerabilities that NVD files against PHP, that PHP's ChangeLogs name or that php-src publishes as security advisories, from {years[0]} to {years[-1]}. "
        f"{len(tracked)} of them are in parts of PHP that Phego ships or plans to ship, and each of those names the Phego work package that has to cover it.",
        "",
        f"**{len(tested)} already have regression cases.** On every commit, CI runs {cases} PHP programs that replay the original triggers through the parts of Phego's VM built so far "
        "and compares the output byte for byte with patched PHP 8.5.12 on 64-bit ARM, 64-bit x86 and 32-bit x86. "
        f"For {partial} of these {len(tested)}, the cases cover only part of the advisory, and the catalog says which part.",
        "",
        f"{memory} of the {len(tracked)} are memory-safety bugs in PHP's C code, such as buffer overflows and use-after-free. "
        "Phego's default build is Go without cgo or unsafe code, so the Go runtime checks every slice bound and frees memory only once nothing refers to it. "
        "The result of the same input can still be wrong, so each case checks that it ends the way patched PHP ends it, not in a panic, a hang or a different value.",
        "",
        f"The other {pending} still need a case. Most wait for their component to be built. "
        "The ones in components that already run wait for a feature their trigger needs, such as memory metering or error handlers, and the catalog says which. "
        "By the work package of their component: "
        + ", ".join(f"{n} for {wp}" for wp, n in sorted(by_wp.items(), key=lambda kv: (-kv[1], kv[0]))) + ".",
        "",
        "| Status | Vulnerabilities |",
        "|---|---|",
        f"| Regression case passing in CI | {len(tested)} |",
        f"| Waiting for a case | {pending} |",
        f"| In a component Phego does not ship (Apache and other in-server modules) | {doc['totals']['not-provided']} |",
        f"| Not in PHP itself (an application, a PECL extension or a server PHP talks to) | {doc['totals']['excluded']} |",
        "",
        "Every entry is in [the catalog](engineering/compatibility/php-cve-catalog.json), and [the regression corpus](tests/security/php-cve/README.md) explains how a case is written. "
        "A passing case shows that Phego handles that trigger as patched PHP does. It does not prove Phego free of the whole class of bug.",
        README_END,
    ]
    return "\n".join(lines) + "\n"


def splice_readme(text, block):
    if README_BEGIN in text:
        head, rest = text.split(README_BEGIN, 1)
        if README_END not in rest:
            raise ValueError("README.md has the begin marker without the end marker")
        tail = rest.split(README_END, 1)[1].lstrip("\n")
        return head + block + "\n" + tail
    anchor = "## Project status"
    if anchor not in text:
        raise ValueError(f"README.md has no {anchor!r} heading to insert the block before")
    head, tail = text.split(anchor, 1)
    return head + block + "\n" + anchor + tail


def check_cases(doc):
    """Every case file names catalog entries that list it, and back."""
    problems = []
    listed = {}
    for e in doc["entries"]:
        for case in e["tests"]:
            listed.setdefault(case, set()).add(e["id"])
    files = {p.stem: p for p in CASES.glob("*.php")} if CASES.exists() else {}
    for name, path in sorted(files.items()):
        header = set(re.findall(r"^// (?:CVE|GHSA): (\S+)$", path.read_text(), re.M))
        if not header:
            problems.append(f"{path.name}: no '// CVE: <id>' line")
        if header != listed.get(name, set()):
            problems.append(f"{path.name}: names {sorted(header)}, the triage lists it for {sorted(listed.get(name, set()))}")
    for name in sorted(set(listed) - set(files)):
        problems.append(f"triage lists case {name}, which is not in {CASES.relative_to(ROOT)}")
    return problems


def check_sources(doc):
    """Every identifier a source yielded is an entry or an entry's alias."""
    known = {e["id"] for e in doc["entries"]} | {a for e in doc["entries"] for a in e["aliases"]}
    return [f"{ident} from {source} is not in the catalog"
            for source, ids in doc["sources"]["ids"].items() for ident in ids if ident not in known]


def check_assessments(doc):
    """Every identifier in security-assessments.json is a catalog entry or alias."""
    known = {e["id"] for e in doc["entries"]} | {a for e in doc["entries"] for a in e["aliases"]}
    data = json.loads(ASSESSMENTS.read_text())
    return [f"{ASSESSMENTS.name}: {i} ({r['release']}) is not in the catalog"
            for r in data["assessments"] for i in r["ids"] if i not in known]


def build(cache, write_readme=True):
    nvd, changelog, advisories = load_sources(cache)
    manifest = json.loads((cache / "manifest.json").read_text())
    records = extract(nvd, changelog, advisories)
    triage = load_triage()
    extras = triage.get("additional_sources", {})
    # An identifier the fetched pages omit, taken from php-src NEWS; the GHSA
    # aliases it lists stop being entries of their own and lend it their
    # ChangeLog lines.
    absorbed = {a: records.pop(a) for extra in extras.values() for a in extra.get("aliases", []) if a in records}
    for ident, extra in extras.items():
        rec = records.setdefault(ident, {"id": ident, "aliases": [], "sources": []})
        for alias in extra.get("aliases", []):
            gone = absorbed.get(alias)
            if gone and not rec.get("changelog"):
                rec["changelog"] = gone.get("changelog", [])
                rec["fixed_in"] = gone.get("fixed_in", [])
                rec["sources"] = sorted(set(rec["sources"]) | set(gone["sources"]))
        rec["aliases"] = sorted(set(rec["aliases"]) | set(extra.get("aliases", [])))
        rec["sources"] = sorted(set(rec["sources"]) | {"php-src-news"})
        rec["fixed_in"] = sorted(set(rec.get("fixed_in", [])) | set(extra["fixed_in"]), key=version_key)
        rec.setdefault("changelog", [{"section": extra["section"], "text": extra["text"]}])
        rec["news_reference"] = extra["reference"]
    upstream_tests(records, (cache / PHP_SOURCE_LIST).read_text())
    # Every identifier each source yielded, so check can tell when an entry
    # is dropped from the catalog.
    ids = {"nvd": sorted(nvd, key=id_key), "php.net-changelog": sorted(changelog, key=id_key),
           "php-src-advisory": sorted(set(advisories) | {a["cve"] for a in advisories.values() if a["cve"]}, key=id_key),
           "php-src-news": sorted(extras, key=id_key)}
    sources = {"fetched_at": manifest["fetched_at"], "files": manifest["files"], "ids": ids}
    doc = document(catalog_entries(records, triage), sources)
    problems = check_cases(doc) + check_assessments(doc) + check_sources(doc)
    if problems:
        raise ValueError("\n  ".join(["catalog is inconsistent:"] + problems))
    CATALOG.write_text(encode(doc))
    if write_readme:
        README.write_text(splice_readme(README.read_text(), readme_block(doc)))
    return doc


def check():
    """Rebuild the catalog from its own source fields and the triage, offline."""
    doc = json.loads(CATALOG.read_text())
    records = {}
    keep = ("id", "aliases", "sources", "published", "nvd_status", "cwe", "summary", "php_vulnerable_in_nvd",
            "nvd_products", "fixed_in", "changelog", "news_reference", "php_src_tests")
    for e in doc["entries"]:
        records[e["id"]] = {k: e[k] for k in keep if k in e}
    rebuilt = document(catalog_entries(records, load_triage()), doc["sources"])
    problems = []
    if encode(rebuilt) != encode(doc):
        old = {e["id"]: e for e in doc["entries"]}
        for e in rebuilt["entries"]:
            if old.get(e["id"]) != e:
                problems.append(f"{e['id']} differs from the rules and triage; run build")
        if not problems:
            problems.append("catalog totals or header differ; run build")
    problems += check_cases(doc) + check_assessments(doc) + check_sources(doc)
    block = readme_block(doc)
    if block not in README.read_text():
        problems.append("README.md block is stale; run build")
    return doc, problems


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    f = sub.add_parser("fetch", help="download NVD and the php.net ChangeLogs")
    f.add_argument("--cache", type=Path, required=True, help="directory for the downloaded sources")
    b = sub.add_parser("build", help="write the catalog and the README block from the cached sources")
    b.add_argument("--cache", type=Path, required=True, help="directory fetch wrote")
    sub.add_parser("check", help="verify the committed catalog, cases and README offline")
    args = parser.parse_args(argv)
    try:
        if args.command == "fetch":
            fetch(args.cache)
        elif args.command == "build":
            doc = build(args.cache)
            print(f"catalog: {json.dumps(doc['totals'])}")
        else:
            doc, problems = check()
            if problems:
                print("php-cve-catalog check failed:\n  " + "\n  ".join(problems), file=sys.stderr)
                return 1
            print(f"PASS: {doc['totals']['entries']} catalog entries, {json.dumps(doc['totals'])}")
    except (OSError, ValueError, KeyError) as exc:
        print(f"php-cve-catalog {args.command} failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
