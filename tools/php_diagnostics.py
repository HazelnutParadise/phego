#!/usr/bin/env python3
"""Reproduce the PHP 8.5.12 grammar data used by Go syntax diagnostics."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
SOURCE_SHA256 = "502e67f51b0e51828ead82fe228ee5d550d5d3e7e05cc11119df40df1a7ceda3"


def generate(source: bytes, token_source: str) -> dict:
    """Extract data from the locked release; never compile or execute its C code."""
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError("source SHA-256 differs from the locked PHP 8.5.12 parser")
    text = source.decode("utf-8")

    def array(name):
        match = re.search(r"\b" + name + r"\[\]\s*=\s*\{(.*?)\};", text, re.S)
        if match is None:
            raise ValueError("missing parser array: " + name)
        return [int(x) for x in re.findall(r"-?\d+", match[1])]

    pact, default, pgo, dgo, table, check, r1, r2, translate = map(array, [
        "yypact", "yydefact", "yypgoto", "yydefgoto", "yytable", "yycheck",
        "yyr1", "yyr2", "yytranslate",
    ])
    raw = re.search(r"\byytname\[\]\s*=\s*\{(.*?)\};", text, re.S)[1]
    # Scan C string literals before commas: ',' is itself a token name.
    names, current = [], ""
    for item in re.findall(r'"(?:\\.|[^"\\])*"|,|YY_NULLPTR', raw):
        if item == ",":
            names.append(current)
            current = ""
        elif item == "YY_NULLPTR":
            break
        else:
            current += json.loads(item)
    terminals = 185
    if len(pact) != 1205 or len(r1) != 636 or len(names) != terminals + len(pgo):
        raise ValueError("unexpected PHP parser table dimensions")
    labels = []
    for name in names[:terminals]:
        if name.startswith('"') and name.endswith('"'):
            name = name[1:-1]
        if name == "'\\\\'":
            name = "'\\'"
        labels.append(name)

    # Convert displacement tables to sorted sparse rows. Retain default-only
    # states: their reductions occur before the scanner reads another token.
    states, actions = [], []
    for index, displacement in enumerate(pact):
        row = []
        if displacement != -937:
            for token in range(terminals):
                at = displacement + token
                if 0 <= at < len(check) and check[at] == token:
                    value = table[at]
                    row.append((token, 0 if value == -607 else value))
        states.append((len(actions), len(row) | (0x8000 if displacement == -937 else 0), default[index]))
        actions.extend(row)
    gotos, jumps = [], []
    for index, displacement in enumerate(pgo):
        row = []
        for state in range(len(states)):
            at = displacement + state
            if 0 <= at < len(check) and check[at] == state:
                row.append((state, table[at]))
        gotos.append((len(jumps), len(row), dgo[index]))
        jumps.extend(row)

    match = re.search(r"var kindNames = .*?\{(.*?)\n\}", token_source, re.S)
    if match is None:
        raise ValueError("missing Go token names")
    kind_names = re.findall(r'"(T_[A-Z_]+)"', match[1])
    symbols = {name: int(value) for name, value in re.findall(r"YYSYMBOL_(T_[A-Z_]+)\s*=\s*(\d+)", text)}
    symbols["T_DOUBLE_COLON"] = symbols["T_PAAMAYIM_NEKUDOTAYIM"]
    kind_map = [translate[i] if i < len(translate) else 2 for i in range(256)]
    kind_map.extend(symbols.get(name, 2) for name in kind_names)
    kind_map[256 + kind_names.index("T_CLOSE_TAG")] = translate[ord(";")]
    kind_map[256 + kind_names.index("T_OPEN_TAG_WITH_ECHO")] = symbols["T_ECHO"]

    guard_names, guards = diagnostic_guards(text, r2)
    if len(guards) != 18:
        raise ValueError("unexpected PHP diagnostic action count")

    data, offsets = bytearray(), {}

    def put(name, fmt, records):
        offsets[name] = len(data)
        for row in records:
            data.extend(struct.pack("<" + fmt, *row))

    put("State", "IHH", states)
    put("Rule", "HHHH", [(max(0, a - terminals), b, *guards.get(i, (0, 0))) for i, (a, b) in enumerate(zip(r1, r2))])
    put("Goto", "IHH", gotos)
    put("Action", "Hh", actions)
    put("Jump", "HH", jumps)
    put("Symbol", "H", [(x,) for x in kind_map])
    put("Name", "IH", [(0, 0) for _ in labels])
    for index, name in enumerate(labels):
        encoded = name.encode("utf-8")
        struct.pack_into("<IH", data, offsets["Name"] + 6 * index, len(data), len(encoded))
        data.extend(encoded)
    lines = [
        "// Code generated by tools/php_diagnostics.py. DO NOT EDIT.",
        "// Grammar-derived data: Copyright Zend Technologies Ltd.; Zend Engine License 2.00.",
        "// See third_party/php-sort/Zend-LICENSE and third_party/php-diagnostics/UPSTREAM.json.",
        "package frontend", 'import _ "embed"', "//go:embed php8512_diagnostics.bin",
        "var diagnosticData string", "const (",
    ]
    lines.extend(f"diagnostic{key}Offset = {value}" for key, value in offsets.items())
    counts = dict(StateCount=len(states), RuleCount=len(r1), GotoCount=len(gotos),
                  ActionCount=len(actions), JumpCount=len(jumps), SymbolCount=len(kind_map),
                  NameCount=len(labels), FinalState=3, ErrorSymbol=symbols["T_ERROR"])
    lines.extend(f"diagnostic{key} = {value}" for key, value in counts.items())
    lines.extend(f"diagnosticGuard{key} = {index}" for index, key in enumerate(guard_names))
    lines.append(")")
    formatted = subprocess.run(["gofmt"], input="\n".join(lines) + "\n", text=True,
                               capture_output=True, check=True).stdout.encode()
    return {"php8512_diagnostics.bin": bytes(data), "diagnostics_generated.go": formatted}


def diagnostic_guards(text: str, r2: list[int]):
    """Select only the operand used by each PHP diagnostic action."""
    blocks = list(re.finditer(r"(?m)^  case (\d+):", text))
    # Each guard consumes only its designated RHS operand, except class
    # modifier accumulation which checks the whole ordered modifier range.
    guard_names = ["None", "Identifier", "Halt", "InnerHalt", "Encoding", "Class",
                   "AnonymousClass", "Property", "Method", "Constant", "Parameter", "PropertyHook"]
    guards = {}
    targets = {"PROPERTY": "Property", "METHOD": "Method", "CONSTANT": "Constant",
               "CPP": "Parameter", "PROPERTY_HOOK": "PropertyHook"}
    for index, match in enumerate(blocks):
        end = blocks[index + 1].start() if index + 1 < len(blocks) else len(text)
        body = text[match.end():end]
        rule = int(match[1])
        kind, operand = "None", 0
        ident = re.search(r"zend_lex_tstring\(&zv, \(yyvsp\[(-?\d+)\]\.ident\)\)", body)
        modifier = re.search(r"zend_modifier_(?:list_to_flags|token_to_flag)\(ZEND_MODIFIER_TARGET_(\w+), \(yyvsp\[(-?\d+)\]\.(?:ast|num)\)\)", body)
        if ident:
            kind, operand = "Identifier", r2[rule] - 1 + int(ident[1])
        elif modifier:
            kind, operand = targets[modifier[1]], r2[rule] - 1 + int(modifier[2])
        elif "zend_stop_lexing" in body:
            kind = "Halt"
        elif "__HALT_COMPILER() can only be used" in body:
            kind = "InnerHalt"
        elif "zend_handle_encoding_declaration" in body:
            kind = "Encoding"
        elif "zend_add_class_modifier" in body:
            kind = "Class"
        elif "zend_add_anonymous_class_modifier" in body:
            kind = "AnonymousClass"
        if kind == "None" and ("zend_lex_tstring" in body or "zend_modifier_" in body):
            raise ValueError("unrecognized diagnostic operand in rule " + str(rule))
        if kind != "None":
            if kind not in {"Encoding", "Class", "AnonymousClass", "Halt", "InnerHalt"} and not 0 <= operand < r2[rule]:
                raise ValueError("diagnostic operand outside rule " + str(rule))
            guards[rule] = (guard_names.index(kind), operand)

    return guard_names, guards

def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, epilog=(
        "Extract Zend/zend_language_parser.c from the archive pinned in compat.lock.json. "
        "Requires Python 3 and gofmt; neither PHP nor Bison runs during generation. "
        "Example: python3 tools/php_diagnostics.py --source /tmp/php-8.5.12/Zend/zend_language_parser.c --check"))
    parser.add_argument("--source", type=Path, required=True, help="locked PHP 8.5.12 generated C parser")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "internal/frontend", help="generated file directory (default: internal/frontend)")
    parser.add_argument("--check", action="store_true", help="verify identical output without writing")
    args = sys.argv[1:] if argv is None else argv
    if not args:
        parser.print_help()
        return 0
    options = parser.parse_args(args)
    try:
        generated = generate(options.source.read_bytes(), (ROOT / "internal/frontend/token.go").read_text())
        if options.check:
            for name, data in generated.items():
                if (options.output_dir / name).read_bytes() != data:
                    raise ValueError("generated data differs: " + name)
        else:
            options.output_dir.mkdir(parents=True, exist_ok=True)
            for name, data in generated.items():
                (options.output_dir / name).write_bytes(data)
        print(json.dumps({name: {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
                          for name, data in generated.items()}, sort_keys=True))
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
