"""Generate internal/profile/releases_gen.go from the PHP release inventory.

The engine must tell a known PHP release it does not implement yet from a
version string that names no release at all. The inventory is the record of
known releases, so the Go table is generated from it rather than kept by hand.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "docs/compatibility/php-release-inventory.json"
OUTPUT = ROOT / "internal/profile/releases_gen.go"


def render(inventory):
    lines = [
        "// Code generated by tools/profile_releases.py from",
        "// docs/compatibility/php-release-inventory.json; DO NOT EDIT.",
        "",
        "package profile",
        "",
        "// knownReleases lists every release recorded in the PHP release",
        "// inventory with its language generation, in inventory order.",
        "var knownReleases = []knownRelease{",
    ]
    seen = set()
    for release in inventory["releases"]:
        version, generation = release["version"], release["generation"]
        if version in seen:
            raise ValueError(f"duplicate release {version!r} in inventory")
        seen.add(version)
        lines.append(f"\t{{{json.dumps(version)}, {json.dumps(generation)}}},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = parser.parse_args(argv)
    text = render(json.loads(INVENTORY.read_text(encoding="utf-8")))
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run python3 tools/profile_releases.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
