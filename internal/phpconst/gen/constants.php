<?php
// Writes constants_<width>_gen.go: every constant defined under php -n in
// the running PHP, as Phego's predefined constant table for that integer
// width. Run through the go:generate lines in phpconst.go, inside a pinned
// PHP 8.5.12 image, never from tests.
//
// Each entry carries the name in the form zend_register_constant stores it
// (the namespace part lower-cased, the constant's own name as written),
// the value, and for a constant PHP marks deprecated the exact message its
// use raises. STDIN, STDOUT and STDERR are resources, which the table can
// only name. CHAR_MAX and PHP_BUILD_DATE differ between the arm64 and amd64
// images of the same width (127 vs 255; the build timestamps), so they are
// recorded as platform-dependent: Phego's profile has no CPU architecture
// yet, and a program that reads them is refused rather than guessed.

$platform = ['CHAR_MAX' => true, 'PHP_BUILD_DATE' => true];

function key_form(string $name): string
{
    $slash = strrpos($name, '\\');
    if ($slash === false) {
        return $name;
    }
    return strtolower(substr($name, 0, $slash)) . substr($name, $slash);
}

function go_quote(string $s): string
{
    $out = '"';
    for ($i = 0, $n = strlen($s); $i < $n; $i++) {
        $c = $s[$i];
        $o = ord($c);
        if ($c === '"' || $c === '\\') {
            $out .= '\\' . $c;
        } elseif ($o >= 0x20 && $o <= 0x7e) {
            $out .= $c;
        } else {
            $out .= sprintf('\\x%02x', $o);
        }
    }
    return $out . '"';
}

$all = get_defined_constants();
$rows = [];
foreach ($all as $name => $value) {
    $rows[key_form($name)] = [$name, $value];
}
ksort($rows, SORT_STRING);

$width = PHP_INT_SIZE * 8;
echo "// Code generated by gen/constants.php; DO NOT EDIT.\n";
echo "//\n";
echo "// Source: get_defined_constants() of PHP ", PHP_VERSION, " under php -n in the pinned\n";
echo "// ", $width, "-bit image (", php_uname('m'), "), ", count($rows), " constants; see the go:generate\n";
echo "// lines in phpconst.go for the image and the command.\n";
echo "\n";
echo "package phpconst\n\n";
echo "import \"math\"\n\n";
echo "var table", $width, " = []Constant{\n";
foreach ($rows as $key => [$name, $value]) {
    $fields = ['Name: ' . go_quote($key)];
    if (isset($platform[$name])) {
        $fields[] = 'Kind: Platform';
    } else {
        switch (gettype($value)) {
            case 'NULL':
                $fields[] = 'Kind: Null';
                break;
            case 'boolean':
                $fields[] = 'Kind: Bool';
                if ($value) {
                    $fields[] = 'Bool: true';
                }
                break;
            case 'integer':
                $fields[] = 'Kind: Int';
                if ($value !== 0) {
                    $fields[] = 'Int: ' . $value;
                }
                break;
            case 'double':
                $fields[] = 'Kind: Float';
                $fields[] = 'Float: math.Float64frombits(0x' . bin2hex(pack('E', $value)) . ')';
                break;
            case 'string':
                $fields[] = 'Kind: String';
                if ($value !== '') {
                    $fields[] = 'Str: ' . go_quote($value);
                }
                break;
            case 'resource':
                $fields[] = 'Kind: Resource';
                break;
            default:
                fwrite(STDERR, "unexpected constant type for $name\n");
                exit(1);
        }
        $r = new ReflectionConstant($name);
        if ($r->isDeprecated()) {
            $message = null;
            set_error_handler(function (int $level, string $text) use (&$message): bool {
                $message = [$level, $text];
                return true;
            });
            constant($name);
            restore_error_handler();
            if ($message === null || $message[0] !== E_DEPRECATED) {
                fwrite(STDERR, "deprecated constant $name raised no E_DEPRECATED\n");
                exit(1);
            }
            $fields[] = 'Deprecated: ' . go_quote($message[1]);
        }
    }
    echo "\t{", implode(', ', $fields), "},\n";
}
echo "}\n";
