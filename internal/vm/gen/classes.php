<?php
// Writes classes_gen.go: the classes, interfaces, traits and enums the
// running PHP declares before any script runs, lower-cased and sorted. Run
// inside the pinned PHP 8.5.12 image with php -n, never from tests.
$names = array_map('strtolower', array_merge(get_declared_classes(), get_declared_interfaces(), get_declared_traits()));
$names = array_values(array_unique($names));
sort($names, SORT_STRING);
echo "// Code generated by gen/classes.php; DO NOT EDIT.\n";
echo "//\n";
echo "// Source: get_declared_classes(), get_declared_interfaces() and\n";
echo "// get_declared_traits() of PHP ", PHP_VERSION, " under php -n in\n";
echo "// php@sha256:add6a138b6bd07edd645088917c081579f6e0d52d3c4361aff9d9309e6ebf9d9 (", php_uname('m'), "),\n";
echo "// lower-cased and sorted. Command (from internal/vm):\n";
echo "//\n";
echo "//\tdocker run --rm --network none --cap-drop ALL -v \"\$PWD/gen\":/g:ro \\\n";
echo "//\t  php@sha256:add6a138b6bd07edd645088917c081579f6e0d52d3c4361aff9d9309e6ebf9d9 \\\n";
echo "//\t  php -n /g/classes.php > classes_gen.go\n";
echo "\n";
echo "package vm\n\n";
echo "// ", count($names), " names.\n";
echo "var builtinClasses = []string{\n";
foreach ($names as $n) {
    echo "\t", json_encode($n, JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR), ",\n";
}
echo "}\n";
