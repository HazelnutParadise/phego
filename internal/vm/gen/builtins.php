echo "// lower-cased and sorted. Command (from internal/vm):\n";
echo "//\n";
echo "//\tdocker run --rm --network none --cap-drop ALL -v \"\$PWD/gen\":/g:ro \\\n";
echo "//\t  php@sha256:add6a138b6bd07edd645088917c081579f6e0d52d3c4361aff9d9309e6ebf9d9 \\\n";
echo "//\t  php -n /g/builtins.php > builtins_gen.go\n";
echo "\n";
echo "package vm\n\n";
echo "// ", count($names), " names.\n";
echo "var builtinFunctions = []string{\n";
foreach ($names as $n) {
    // JSON escapes the backslash of namespaced names (dom\import_simplexml)
    // the way a Go string literal needs; the names are ASCII identifiers.
    echo "\t", json_encode($n, JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR), ",\n";
}
echo "}\n";
