// Writes throwables_gen.go: the classes of PHP 8.5.12's Core and SPL
// extensions that implement Throwable, parents first, with the parent of
// each. Run through the go:generate line in vm_exception.go.
$image = 'php@sha256:add6a138b6bd07edd645088917c081579f6e0d52d3c4361aff9d9309e6ebf9d9';
$handBuilt = ['Exception' => 1, 'Error' => 1, 'ErrorException' => 1];
// FiberError has a constructor of its own that refuses to run; it comes
// with fibers.
$skip = ['FiberError' => 1];
$rows = [];
foreach (get_declared_classes() as $name) {
    $r = new ReflectionClass($name);
    if (isset($skip[$name]) || !$r->implementsInterface('Throwable') || !in_array($r->getExtensionName(), ['Core', 'SPL'], true)) {
        continue;
    }
    $own = 0;
    foreach ($r->getMethods() as $m) {
        $own += $m->getDeclaringClass()->getName() === $name ? 1 : 0;
    }
    foreach ($r->getProperties() as $p) {
        $own += $p->getDeclaringClass()->getName() === $name ? 1 : 0;
    }
    if ($own !== 0 && !isset($handBuilt[$name])) {
        fwrite(STDERR, "$name declares members of its own\n");
        exit(1);
    }
    $parent = $r->getParentClass();
    $rows[] = [$name, $parent ? $parent->getName() : '', $r->isFinal(), $r->getExtensionName()];
}
// Parents first: by depth, then by name.
$depth = function ($name) use (&$depth, $rows) {
    foreach ($rows as $row) {
        if ($row[0] === $name) {
            return $row[1] === '' ? 0 : 1 + $depth($row[1]);
        }
    }
    return 0;
};
usort($rows, fn($a, $b) => [$depth($a[0]), $a[0]] <=> [$depth($b[0]), $b[0]]);
