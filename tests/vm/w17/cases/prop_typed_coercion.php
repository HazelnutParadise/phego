<?php
class Typed
{
    public int $i = 0;
    public float $f = 0.0;
    public string $s = "";
    public bool $b = false;
    public ?int $ni = null;
    public int|string $u = 0;
    public float|bool $fb = 0.0;
    public array $a = [];
    public ?Typed $self = null;
    public iterable $it = [];
    public mixed $m;
    public self $me;
}

$t = new Typed;
$t->i = "42";
echo "string to int: ", $t->i, "\n";
$t->i = 7.0;
echo "integral float to int: ", $t->i, "\n";
$t->i = true;
echo "bool to int: ", $t->i, "\n";
$t->i = " 12";
echo "leading whitespace: ", $t->i, "\n";
$t->f = 3;
echo "int to float: ", $t->f, "\n";
$t->f = "2.5";
echo "string to float: ", $t->f, "\n";
$t->s = 15;
echo "int to string: ", $t->s, "\n";
$t->s = 1.25;
echo "float to string: ", $t->s, "\n";
$t->s = false;
echo "false to string: [", $t->s, "]\n";
$t->b = "0";
echo "\"0\" to bool: ", ($t->b ? "true" : "false"), "\n";
$t->b = 2;
echo "2 to bool: ", ($t->b ? "true" : "false"), "\n";
$t->ni = null;
echo "null to ?int: ", ($t->ni === null ? "null" : "set"), "\n";
$t->ni = "5";
echo "string to ?int: ", $t->ni, "\n";
$t->u = "9";
echo "union keeps string: ", ($t->u === "9" ? "string" : "other"), "\n";
$t->u = 9.0;
echo "union float to int: ", ($t->u === 9 ? "int" : "other"), "\n";
$t->u = 9.5;
echo "union fractional float: ", $t->u, " ", ($t->u === 9 ? "int" : ($t->u === "9.5" ? "string" : "other")), "\n";
$t->fb = 3;
echo "float|bool from int: ", ($t->fb === 3.0 ? "float" : "other"), "\n";
$t->fb = "x";
echo "float|bool from non-numeric string: ", ($t->fb === true ? "bool" : "other"), "\n";
$t->self = new Typed;
echo "class type: ", ($t->self instanceof Typed ? "ok" : "no"), "\n";
$t->me = $t;
echo "self type: ", ($t->me === $t ? "ok" : "no"), "\n";
$t->m = null;
echo "mixed null: ", ($t->m === null ? "ok" : "no"), "\n";
$t->i = 1.5;
echo "fractional float to int: ", $t->i, "\n";
$t->i++;
echo "increment typed: ", $t->i, "\n";
$t->s .= 5;
echo "concat assign: ", $t->s, "\n";
$t->f += 1;
echo "float compound: ", $t->f, "\n";
$t->a[] = "x";
echo "array append: ", $t->a[0], "\n";
