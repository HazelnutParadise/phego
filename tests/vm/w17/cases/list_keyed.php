<?php
['a' => $a, 'b' => $b] = ['a' => 1, 'b' => 2];
echo $a, $b, "\n";
list('x' => $x, 'y' => $y) = ['y' => 'Y', 'x' => 'X'];
echo $x, $y, "\n";
[1 => $one, 0 => $zero] = ['z', 'o'];
echo $one, $zero, "\n";
['1' => $e, '01' => $f] = [1 => 'one', '01' => 'zero-one'];
echo $e, " ", $f, "\n";
$k = 'key';
[$k => $g] = ['key' => 'G'];
echo $g, "\n";
[$k . '2' => $h] = ['key2' => 'H'];
echo $h, "\n";
[1.5 => $i] = [1 => 'I'];
echo $i, "\n";
[true => $j] = [1 => 'J'];
echo $j, "\n";
[null => $l] = ['' => 'L'];
echo $l, "\n";
[false => $m] = [0 => 'M'];
echo $m, "\n";
["" => $n] = ["" => 'N'];
echo $n, "\n";
[-1 => $o] = [-1 => 'O'];
echo $o, "\n";
["-1" => $p] = [-1 => 'P'];
echo $p, "\n";
["1.0" => $q] = ["1.0" => 'Q'];
echo $q, "\n";
