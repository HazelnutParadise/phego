<?php
$a = 1; $b = 2;
[$a, $b] = [$b, $a];
echo $a, $b, "\n";
$x = [1, 2];
[$x[0], $x[1]] = [$x[1], $x[0]];
echo $x[0], $x[1], "\n";
$arr = [1, 2, 3];
[$arr[0], $arr[1]] = $arr;
echo $arr[0], $arr[1], $arr[2], "\n";
[$z, $z] = [1, 2];
echo $z, "\n";
$w = [3, 4];
[$w, $v] = $w;
echo $w, $v, "\n";
$q = [1, [2]];
[$q[1][0], $q[0]] = $q;
echo $q[0][0], $q[1][0], "\n";
$r = [[1], 2];
[[$r[1]], $r[0]] = $r;
echo $r[0], $r[1], "\n";
$s = [10, 20];
[$s[1], $s[0]] = $s;
echo $s[0], $s[1], "\n";
$t = ['a' => [1]];
['a' => [$t]] = $t;
echo $t, "\n";
$u = [5];
[$u[]] = $u;
echo $u[0], $u[1], "\n";
